import assert from 'node:assert/strict'
import { after, describe, test } from 'node:test'

import { Window } from 'happy-dom'

const domWindow = new Window()
for (const key of [
  'window',
  'document',
  'navigator',
  'HTMLElement',
  'SVGElement',
  'Node',
  'Element',
  'Event',
  'CustomEvent',
  'MutationObserver',
  'getComputedStyle',
] as const) {
  Object.defineProperty(globalThis, key, {
    configurable: true,
    value: domWindow[key],
  })
}

const { act } = await import('react')
const { createRoot } = await import('react-dom/client')
const { createInstance } = await import('i18next')
const { I18nextProvider, initReactI18next } = await import('react-i18next')
const { TableEmpty } = await import('../table-empty')

const reactTestGlobals = globalThis as typeof globalThis & {
  IS_REACT_ACT_ENVIRONMENT?: boolean
}
reactTestGlobals.IS_REACT_ACT_ENVIRONMENT = true

const i18n = createInstance()
await i18n.use(initReactI18next).init({
  lng: 'en',
  resources: { en: { translation: {} } },
})

describe('table empty-state layout', () => {
  after(() => domWindow.close())

  test('stays centered in the visible table viewport', async () => {
    const container = document.createElement('table')
    document.body.append(container)
    const root = createRoot(container)

    await act(async () => {
      root.render(
        <I18nextProvider i18n={i18n}>
          <tbody>
            <TableEmpty colSpan={1} />
          </tbody>
        </I18nextProvider>
      )
    })

    const empty = container.querySelector('[data-slot="empty"]')
    assert.ok(empty?.classList.contains('sticky'))
    assert.ok(empty?.classList.contains('left-0'))
    assert.ok(empty?.classList.contains('w-[100cqw]'))

    await act(async () => root.unmount())
    container.remove()
  })
})
